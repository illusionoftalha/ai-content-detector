#!/usr/bin/env python3
"""
AI Content Detector (Groq-powered — free tier)
Detects whether text was written by a human or generated by AI.
Supports pasting text directly, or uploading .txt / .docx files.

Usage:
  python ai_detector.py                  # interactive mode
  python ai_detector.py essay.txt        # analyze a .txt file
  python ai_detector.py report.docx      # analyze a .docx file
  echo "Some text" | python ai_detector.py -   # stdin
"""

import json
import sys
import os
import textwrap
import argparse
from groq import Groq

# ── Set your Groq API key here ──────────────────────────────────────────────
GROQ_API_KEY = ""   # <-- paste your key
# Or set env variable: export GROQ_API_KEY=your_key
# ────────────────────────────────────────────────────────────────────────────

GROQ_MODEL = "llama-3.3-70b-versatile"   # free, fast, accurate

# ── colour helpers ───────────────────────────────────────────────────────────
RESET  = "\033[0m";  BOLD  = "\033[1m";  DIM   = "\033[2m"
RED    = "\033[91m"; ORANGE= "\033[93m"; YELLOW= "\033[33m"
GREEN  = "\033[92m"; CYAN  = "\033[96m"; WHITE = "\033[97m"
GRAY   = "\033[90m"

def color_for_score(score):
    if score >= 75: return RED
    if score >= 50: return ORANGE
    if score >= 30: return YELLOW
    return GREEN

def verdict_color(verdict):
    return {"AI-Generated":RED,"Likely AI":ORANGE,"Mixed":YELLOW,
            "Likely Human":GREEN,"Human-Written":GREEN}.get(verdict, WHITE)

# ── file reading ─────────────────────────────────────────────────────────────
def read_txt(path):
    with open(path, "r", encoding="utf-8", errors="replace") as f:
        return f.read()

def read_docx(path):
    try:
        from docx import Document
    except ImportError:
        sys.exit("python-docx is required: pip install python-docx")
    doc = Document(path)
    return "\n".join(p.text for p in doc.paragraphs if p.text.strip())

def load_file(path):
    ext = os.path.splitext(path)[1].lower()
    if ext == ".txt":  return read_txt(path)
    if ext == ".docx": return read_docx(path)
    sys.exit(f"Unsupported file type '{ext}'. Use .txt or .docx")

# ── Groq analysis ─────────────────────────────────────────────────────────────
SYSTEM_PROMPT = """You are an expert AI content detector. Analyze the provided text and determine whether it was written by a human or generated by AI (ChatGPT, Claude, Gemini, etc.).

Return ONLY a JSON object — no markdown, no backticks, no explanation outside JSON:
{
  "verdict": "AI-Generated" | "Likely AI" | "Mixed" | "Likely Human" | "Human-Written",
  "confidence": <0-100>,
  "ai_probability": <0-100>,
  "indicators": {
    "ai_signals": ["list specific AI-like patterns found"],
    "human_signals": ["list specific human-like patterns found"]
  },
  "sentence_analysis": [
    {"text": "<first ~80 chars of sentence>", "score": <0-100 AI probability>, "flag": "ai"|"human"|"neutral"}
  ],
  "summary": "<2-3 sentence explanation of the verdict>"
}

Analyze vocabulary, sentence structure, repetition patterns, coherence, naturalness, and stylistic consistency."""

def analyze(text):
    api_key = GROQ_API_KEY if GROQ_API_KEY and GROQ_API_KEY != "YOUR_GROQ_API_KEY_HERE" \
              else os.environ.get("GROQ_API_KEY", "")
    if not api_key:
        sys.exit("No API key found. Set GROQ_API_KEY in the script or as an env variable.")

    client = Groq(api_key=api_key)
    response = client.chat.completions.create(
        model=GROQ_MODEL,
        max_tokens=1500,
        messages=[
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user",   "content": f"Analyze this text:\n\n{text[:6000]}"}
        ],
        temperature=0.1,
    )
    raw = response.choices[0].message.content or ""
    raw = raw.replace("```json", "").replace("```", "").strip()
    return json.loads(raw)

# ── terminal display ──────────────────────────────────────────────────────────
TERM_WIDTH = min(os.get_terminal_size().columns if sys.stdout.isatty() else 80, 100)

def divider(char="─"):
    print(GRAY + char * TERM_WIDTH + RESET)

def bar(score, width=30):
    filled = round(score / 100 * width)
    col = color_for_score(score)
    return col + "█" * filled + GRAY + "░" * (width - filled) + RESET

def print_result(result):
    verdict       = result.get("verdict", "Unknown")
    confidence    = result.get("confidence", 0)
    ai_prob       = result.get("ai_probability", 0)
    summary       = result.get("summary", "")
    ai_signals    = result.get("indicators", {}).get("ai_signals", [])
    human_signals = result.get("indicators", {}).get("human_signals", [])
    sentences     = result.get("sentence_analysis", [])

    vcol = verdict_color(verdict)
    scol = color_for_score(ai_prob)

    print(); divider("═")
    print(f"  {BOLD}{WHITE}AI CONTENT DETECTOR — RESULTS{RESET}")
    divider("═")

    print(f"\n  {BOLD}Verdict    {RESET}  {vcol}{BOLD}{verdict}{RESET}")
    print(f"  {BOLD}AI Prob.   {RESET}  {bar(ai_prob)}  {scol}{BOLD}{ai_prob}%{RESET}")
    print(f"  {BOLD}Confidence {RESET}  {bar(confidence, 20)}  {CYAN}{confidence}%{RESET}\n")

    divider()
    print(f"\n  {BOLD}Summary{RESET}")
    for line in textwrap.wrap(summary, TERM_WIDTH - 4):
        print(f"  {GRAY}{line}{RESET}")
    print()

    divider()
    col_w = (TERM_WIDTH - 6) // 2
    print(f"\n  {RED}{BOLD}🤖 AI Signals{RESET}    {GREEN}{BOLD}🧑 Human Signals{RESET}")
    for i in range(max(len(ai_signals), len(human_signals), 1)):
        ai_s  = textwrap.shorten(ai_signals[i]    if i < len(ai_signals)    else "", col_w, placeholder="…")
        hum_s = textwrap.shorten(human_signals[i] if i < len(human_signals) else "", col_w, placeholder="…")
        print(f"  {RED}• {ai_s:<{col_w}}{RESET}  {GREEN}• {hum_s}{RESET}")
    print()

    if sentences:
        divider()
        print(f"\n  {BOLD}Sentence-Level Breakdown{RESET}\n")
        for s in sentences[:12]:
            txt   = s.get("text", "")[:70]
            score = s.get("score", 50)
            col   = color_for_score(score)
            print(f"  {GRAY}\"{txt}…\"{RESET}")
            print(f"  {bar(score, 15)}  {col}{score}%{RESET}\n")

    divider("═"); print()

# ── interactive input ─────────────────────────────────────────────────────────
def prompt_multiline():
    print(f"\n  {CYAN}Paste your text below.")
    print(f"  {GRAY}When done, type {WHITE}END{GRAY} on its own line and press Enter:{RESET}\n")
    lines = []
    try:
        while True:
            line = input()
            if line.strip().upper() == "END":
                break
            lines.append(line)
    except EOFError:
        pass
    return "\n".join(lines)

# ── main ──────────────────────────────────────────────────────────────────────
def main():
    parser = argparse.ArgumentParser(description="Detect AI-generated content.")
    parser.add_argument("file", nargs="?", help=".txt or .docx file (omit for interactive)")
    args = parser.parse_args()

    print(f"\n{BOLD}{CYAN}  ╔══════════════════════════════╗")
    print(f"  ║   AI CONTENT DETECTOR v1.0   ║")
    print(f"  ║   Powered by Groq (Free)     ║")
    print(f"  ╚══════════════════════════════╝{RESET}")

    if args.file == "-":
        text = sys.stdin.read()
        print(f"  {GRAY}Reading from stdin…{RESET}")
    elif args.file:
        if not os.path.exists(args.file):
            sys.exit(f"File not found: {args.file}")
        print(f"  {GRAY}Reading {args.file}…{RESET}")
        text = load_file(args.file)
    else:
        print(f"\n  {BOLD}How do you want to provide content?{RESET}")
        print(f"  {CYAN}[1]{RESET} Paste text")
        print(f"  {CYAN}[2]{RESET} Enter a file path (.txt or .docx)")
        choice = input(f"\n  Choice (1/2): ").strip()
        if choice == "2":
            path = input("  File path: ").strip().strip('"').strip("'")
            if not os.path.exists(path):
                sys.exit(f"File not found: {path}")
            print(f"  {GRAY}Reading {path}…{RESET}")
            text = load_file(path)
        else:
            text = prompt_multiline()

    text = text.strip()
    if len(text) < 50:
        sys.exit("  ⚠  Please provide at least 50 characters of text.")

    words = len(text.split())
    print(f"\n  {GRAY}Analyzing {len(text):,} characters / {words:,} words…{RESET}")

    try:
        result = analyze(text)
    except json.JSONDecodeError:
        sys.exit("Error: model returned unexpected output. Try again.")
    except Exception as e:
        sys.exit(f"Error: {e}")

    print_result(result)

if __name__ == "__main__":
    main()
